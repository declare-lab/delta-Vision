#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

PY=${PY:-$ROOT_DIR/.venv/bin/python}
export PYTHONPATH="$ROOT_DIR${PYTHONPATH:+:$PYTHONPATH}"

STAMP=${STAMP:-$(date +%Y%m%d_%H%M%S)}
GROUP_NAME=${GROUP_NAME:-qwen235b_kl_only_${STAMP}}
MODEL_LABEL=${MODEL_LABEL:-qwen3-vl-235b-a22b}
MODEL_PATH=${MODEL_PATH:-$ROOT_DIR/model/Qwen3-VL-235B-A22B-Instruct}
MODEL_ID=${MODEL_ID:-Qwen/Qwen3-VL-235B-A22B-Instruct}

export CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES:-0,1,2,3,4,5,6,7}
DATA_ROOT=${DATA_ROOT:-/lustre-data/leijingdi/code/delta-vision}
IMAGE_ROOT=${IMAGE_ROOT:-$ROOT_DIR/data/train/pixmo}
DATA=${DATA:-$ROOT_DIR/data/train/pixmo/pixmo_ama_full_valid.clean.jsonl}

MAX_STEPS=${MAX_STEPS:-2000}
SAVE_EVERY=${SAVE_EVERY:-$MAX_STEPS}
MAX_SAMPLES=${MAX_SAMPLES:-1000}
BENCHMARKS=${BENCHMARKS:-all}
WANDB=${WANDB:-1}
WANDB_PROJECT=${WANDB_PROJECT:-vision-kv-inject}
WANDB_MODE=${WANDB_MODE:-online}

NPROC_PER_NODE=${NPROC_PER_NODE:-8}
REQUIRED_WORLD_SIZE=${REQUIRED_WORLD_SIZE:-$NPROC_PER_NODE}
NUM_SHARDS=${NUM_SHARDS:-1}

QWEN_DEVICE_MAP=${QWEN_DEVICE_MAP:-none}
QWEN_MAX_MEMORY=${QWEN_MAX_MEMORY:-}
EVAL_QWEN_DEVICE_MAP=${EVAL_QWEN_DEVICE_MAP:-auto}
EVAL_QWEN_MAX_MEMORY=${EVAL_QWEN_MAX_MEMORY:-0=120GiB,1=130GiB,2=130GiB,3=130GiB,4=130GiB,5=130GiB,6=130GiB,7=130GiB,cpu=256GiB}

if [[ "${DOWNLOAD:-1}" == "1" ]]; then
  MODEL_ID="$MODEL_ID" DEST="$MODEL_PATH" PY="$PY" bash scripts/download_qwen235b.sh
fi

RUN_NAME=${RUN_NAME:-${GROUP_NAME}_${MODEL_LABEL}}
OUTPUT_DIR=${OUTPUT_DIR:-$ROOT_DIR/artifacts/experiments/qwen_topk1024_freezeqkv/${RUN_NAME}/checkpoints}
LOG_FILE=${LOG_FILE:-$ROOT_DIR/artifacts/logs/${RUN_NAME}.train.log}

if [[ "${SKIP_TRAIN:-0}" != "1" ]]; then
  echo "=== Train ${MODEL_LABEL} ==="
  env \
    MODEL_KIND=qwen \
    OUTPUT_MODE="${QWEN_OUTPUT_MODE:-embedding_adapter}" \
    MODEL_PATH="$MODEL_PATH" \
    DATA="$DATA" \
    DATA_ROOT="${TRAIN_DATA_ROOT:-$IMAGE_ROOT}" \
    IMAGE_ROOT="$IMAGE_ROOT" \
    CUDA_VISIBLE_DEVICES="$CUDA_VISIBLE_DEVICES" \
    NPROC_PER_NODE="$NPROC_PER_NODE" \
    REQUIRED_WORLD_SIZE="$REQUIRED_WORLD_SIZE" \
    QWEN_DEVICE_MAP="$QWEN_DEVICE_MAP" \
    QWEN_MAX_MEMORY="$QWEN_MAX_MEMORY" \
    MAX_STEPS="$MAX_STEPS" \
    SAVE_EVERY="$SAVE_EVERY" \
    LOG_EVERY="${LOG_EVERY:-5}" \
    MICRO_BATCH_SIZE_PER_GPU="${MICRO_BATCH_SIZE_PER_GPU:-4}" \
    GRADIENT_ACCUMULATION_STEPS="${GRADIENT_ACCUMULATION_STEPS:-1}" \
    DS_CONFIG="${DS_CONFIG:-$ROOT_DIR/configs/ds_zero3.json}" \
    DISTRIBUTED_ENGINE="${DISTRIBUTED_ENGINE:-deepspeed}" \
    PIXEL_AREA_CACHE="${PIXEL_AREA_CACHE:-$ROOT_DIR/artifacts/cache/pixmo_ama_full_valid.clean.pixel_areas.json}" \
    MASTER_PORT="${QWEN_MASTER_PORT:-29560}" \
    LR="${LR:-5e-5}" \
    LR_SCHEDULER="${LR_SCHEDULER:-cosine}" \
    WARMUP_RATIO="${WARMUP_RATIO:-0.03}" \
    WARMUP_START_LR_RATIO="${WARMUP_START_LR_RATIO:-0.0}" \
    MIN_LR_RATIO="${MIN_LR_RATIO:-0.1}" \
    WEIGHT_DECAY="${WEIGHT_DECAY:-0.01}" \
    TEMPERATURE="${TEMPERATURE:-2.0}" \
    KL_TOPK="${KL_TOPK:-1024}" \
    LOSS_NORMALIZATION="${LOSS_NORMALIZATION:-token}" \
    SUPERVISION_LOSS="${SUPERVISION_LOSS:-distill}" \
    LAMBDA_LOGIT="${LAMBDA_LOGIT:-1.0}" \
    VISUAL_ADAPTER_RANK="${VISUAL_ADAPTER_RANK:-128}" \
    WANDB="$WANDB" \
    WANDB_PROJECT="$WANDB_PROJECT" \
    WANDB_MODE="$WANDB_MODE" \
    WANDB_RUN_NAME="$RUN_NAME" \
    RUN_NAME="$RUN_NAME" \
    OUTPUT_DIR="$OUTPUT_DIR" \
    LOG_FILE="$LOG_FILE" \
    bash scripts/train.sh
fi

if [[ "${SKIP_EVAL:-0}" != "1" ]]; then
  echo "=== Eval ${MODEL_LABEL} benchmarks=${BENCHMARKS} max_samples=${MAX_SAMPLES} ==="
  env \
    MODEL_KIND=qwen \
    MODEL_PATH="$MODEL_PATH" \
    CUDA_VISIBLE_DEVICES="$CUDA_VISIBLE_DEVICES" \
    NUM_SHARDS="$NUM_SHARDS" \
    QWEN_DEVICE_MAP="$EVAL_QWEN_DEVICE_MAP" \
    QWEN_MAX_MEMORY="$EVAL_QWEN_MAX_MEMORY" \
    MAX_SAMPLES="$MAX_SAMPLES" \
    RUN_DIR="$OUTPUT_DIR" \
    RUN_NAME="$RUN_NAME" \
    OUT_ROOT="$ROOT_DIR/artifacts/eval/qwen/${GROUP_NAME}/${MODEL_LABEL}" \
    TEACHER_CACHE="${TEACHER_CACHE:-1}" \
    COMPILE_ADAPTER="${COMPILE_ADAPTER:-0}" \
    COMPILE_WARMUP="${COMPILE_WARMUP:-0}" \
    ADAPTER_DECODE_CACHE="${ADAPTER_DECODE_CACHE:-0}" \
    EVAL_BATCH_SIZE="${EVAL_BATCH_SIZE:-1}" \
    EVAL_MAX_BATCH_TOKENS="${EVAL_MAX_BATCH_TOKENS:-0}" \
    bash scripts/eval_benchmark.sh --benchmarks "$BENCHMARKS" --run-dir "$OUTPUT_DIR" --step final
fi

echo "=== Done: ${GROUP_NAME} ==="
